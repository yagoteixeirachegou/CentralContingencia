    "Sequence" bigint GENERATED BY DEFAULT AS IDENTITY,
    "TaskId" uuid NOT NULL,
    "Action" character varying(32) NOT NULL,
    "ActorId" uuid,
    "WorkerId" character varying(100),
    "Attempt" integer NOT NULL,
    "Code" character varying(64),
    "CorrelationId" character varying(64) NOT NULL,
    "OccurredAt" timestamp with time zone NOT NULL,
    CONSTRAINT "PK_WorkTaskEvents" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_WorkTaskEvents_Ids" CHECK ("Id" <> '00000000-0000-0000-0000-000000000000'::uuid AND "TaskId" <> '00000000-0000-0000-0000-000000000000'::uuid)
);


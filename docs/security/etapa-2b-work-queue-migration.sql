CREATE TABLE work."Tasks" (
    "Id" uuid NOT NULL,
    "Type" character varying(64) NOT NULL,
    "Status" character varying(16) NOT NULL,
    "PayloadVersion" integer NOT NULL,
    "Payload" jsonb NOT NULL,
    "Result" jsonb,
    "CreatedAt" timestamp with time zone NOT NULL,
    "StartedAt" timestamp with time zone,
    "CompletedAt" timestamp with time zone,
    "AvailableAt" timestamp with time zone NOT NULL,
    "AttemptCount" integer NOT NULL,
    "MaxAttempts" integer NOT NULL,
    "LastErrorCode" character varying(64),
    "LastError" character varying(300),
    "CorrelationId" character varying(64) NOT NULL,
    "IdempotencyKey" uuid NOT NULL,
    "RequestFingerprint" character varying(64) NOT NULL,
    "CreatedBy" uuid NOT NULL,
    "WorkerId" character varying(100),
    "LeaseUntil" timestamp with time zone,
    "HeartbeatAt" timestamp with time zone,
    "CancelRequestedAt" timestamp with time zone,
    "CancelRequestedBy" uuid,
    CONSTRAINT "PK_Tasks" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Tasks_Attempts" CHECK ("AttemptCount" >= 0 AND "MaxAttempts" BETWEEN 1 AND 10 AND "AttemptCount" <= "MaxAttempts"),
    CONSTRAINT "CK_Tasks_Cancel" CHECK (("CancelRequestedAt" IS NULL) = ("CancelRequestedBy" IS NULL)),
    CONSTRAINT "CK_Tasks_Completed" CHECK (("Status" IN ('Succeeded','Failed','Cancelled','DeadLetter')) = ("CompletedAt" IS NOT NULL)),
    CONSTRAINT "CK_Tasks_Fingerprint" CHECK (length("RequestFingerprint") = 64 AND length(btrim("CorrelationId")) > 0),
    CONSTRAINT "CK_Tasks_Ids" CHECK ("Id" <> '00000000-0000-0000-0000-000000000000'::uuid AND "CreatedBy" <> '00000000-0000-0000-0000-000000000000'::uuid AND "IdempotencyKey" <> '00000000-0000-0000-0000-000000000000'::uuid),
    CONSTRAINT "CK_Tasks_Lease" CHECK (("Status" = 'Running') = ("WorkerId" IS NOT NULL AND "LeaseUntil" IS NOT NULL AND "HeartbeatAt" IS NOT NULL)),
    CONSTRAINT "CK_Tasks_Status" CHECK ("Status" IN ('Pending','Running','Succeeded','Failed','Cancelled','DeadLetter')),
    CONSTRAINT "CK_Tasks_Type" CHECK ("Type" IN ('SimulatedProcessing')),
    CONSTRAINT "CK_Tasks_Version" CHECK ("PayloadVersion" >= 1)
);

